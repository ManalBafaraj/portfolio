function galleryKeydown(event) {
  if (lightboxStage.classList.contains('zoomed') && event.target === lightboxStage) return;
  const previousKey = lang === 'ar' ? 'ArrowRight' : 'ArrowLeft';
  const nextKey = lang === 'ar' ? 'ArrowLeft' : 'ArrowRight';
  if (event.key === previousKey || event.key === nextKey) {
    event.preventDefault();
    selectGallery(galleryIndex + (event.key === nextKey ? 1 : -1));
  } else if (event.key === 'Home' || event.key === 'End') {
    event.preventDefault();
    selectGallery(event.key === 'Home' ? 0 : galleryItems.length - 1);
  }
}
