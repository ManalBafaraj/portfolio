// Preserve vertical page scrolling; a deliberate horizontal swipe changes views.
for (const surface of [galleryMain, document.querySelector('.lightbox-stage')]) {
  let touchStart = null;
  surface.addEventListener('touchstart', event => {
    touchStart = event.touches.length === 1 ? { x: event.touches[0].clientX, y: event.touches[0].clientY } : null;
  }, { passive: true });
  surface.addEventListener('touchend', event => {
    if (!touchStart || event.changedTouches.length !== 1) return;
    const dx = event.changedTouches[0].clientX - touchStart.x;
    const dy = event.changedTouches[0].clientY - touchStart.y;
    if (!lightboxStage.classList.contains('zoomed') && Math.abs(dx) > 50 && Math.abs(dx) > Math.abs(dy) * 1.5) {
      selectGallery(galleryIndex + (dx < 0 ? 1 : -1) * (lang === 'ar' ? -1 : 1));
    }
    touchStart = null;
  }, { passive: true });
  surface.addEventListener('touchcancel', () => { touchStart = null; }, { passive: true });
}

