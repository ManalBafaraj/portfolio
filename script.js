function applyLanguage(value) {
  lang = value === 'en' ? 'en' : 'ar';
  const dict = translations[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.body.classList.toggle('en', lang === 'en');
  for (const [data, attr] of [['i18n',null],['i18n-alt','alt'],['i18n-aria','aria-label']]) {
    document.querySelectorAll('[data-' + data + ']').forEach(el => {
      const value = dict[el.getAttribute('data-' + data)];
      if (value !== undefined) { if (attr) el.setAttribute(attr,value); else el.textContent = value; }
    });
  }
  for (const selector of ['meta[name="description"]', 'meta[property="og:description"]', 'meta[name="twitter:description"]']) {
    document.querySelector(selector).setAttribute('content', dict['meta.description']);
  }
  for (const selector of ['meta[property="og:image:alt"]', 'meta[name="twitter:image:alt"]']) {
    document.querySelector(selector).setAttribute('content', dict['meta.imageAlt']);
  }
  document.querySelector('meta[property="og:locale"]').setAttribute('content', lang === 'ar' ? 'ar_SA' : 'en_US');
  document.querySelector('meta[property="og:locale:alternate"]').setAttribute('content', lang === 'ar' ? 'en_US' : 'ar_SA');
  langToggle.textContent = lang === 'ar' ? 'EN' : 'عربي';
  langToggle.setAttribute('aria-label',dict.language);
  menuLabel();
  if (typeof updateGalleryLanguage === 'function') updateGalleryLanguage();
  try { localStorage.setItem('portfolio_lang',lang); } catch {}
}
